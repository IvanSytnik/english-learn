// packages/db/scripts/build-cefr-j-excluded.ts
//
// Offline, run once per source version (B6.7a): writes the headwords the
// CEFR-J Wordlist lists under a part of speech the import leaves out
// (determiner, modal auxiliary, be-/do-/have-verb, infinitive-to), plus the
// be-/have-verb forms it omits, to data/cefr-j-v1.5-excluded.json — the same
// keys add-cefr-j-shadowed.ts derives (src/vocab/shadowed.ts), grouped by the
// source's tag. The paste import shows them as "function words — not
// practised", never as "not found" (src/vocab/excluded.ts).
//
// Usage (from packages/db; the CSV is not in the repo):
//   pnpm exec tsx scripts/build-cefr-j-excluded.ts path/to/cefrj-vocabulary-profile-1.5.csv

import { readFileSync, writeFileSync } from 'node:fs';
import { csvRecords } from '../src/vocab/cefr-j-csv';
import { CEFR_J_DATASET_URL } from '../src/vocab/dataset';
import { mapCefrJPos } from '../src/vocab/normalize';
import { excludedHeadwordKeys } from '../src/vocab/shadowed';

const EXCLUDED_DATASET_URL = new URL('../data/cefr-j-v1.5-excluded.json', import.meta.url);

const NOTE =
  'Headwords the source lists under a part of speech the import leaves out, all levels, ' +
  'with the be-/have-verb forms it omits (being, having). Generated by ' +
  'scripts/build-cefr-j-excluded.ts from the source CSV; do not edit by hand.';

function main(): void {
  const csvPath = process.argv[2];
  if (!csvPath) throw new Error('Usage: build-cefr-j-excluded.ts <cefrj csv>');
  const records = csvRecords(readFileSync(csvPath, 'utf8'));
  const source = JSON.parse(readFileSync(CEFR_J_DATASET_URL, 'utf8')).source as Record<
    string,
    string
  >;

  const tags = [
    ...new Set(
      records.map((r) => (r.pos ?? '').trim().toLowerCase()).filter((t) => mapCefrJPos(t) === null),
    ),
  ].sort();
  const byPos = Object.fromEntries(
    tags.map((tag) => [
      tag,
      [...excludedHeadwordKeys(records.filter((r) => (r.pos ?? '').trim().toLowerCase() === tag))]
        .sort()
        .map((k) => JSON.stringify(k)),
    ]),
  );
  const total = new Set(Object.values(byPos).flat()).size;
  if (total !== excludedHeadwordKeys(records).size) throw new Error('grouping lost a key');

  // One line per tag: the file stays small and diffs by tag.
  const lines = Object.entries(byPos).map(([tag, keys]) => `    "${tag}": [${keys.join(', ')}]`);
  const head = {
    name: source.name,
    version: source.version,
    citation: source.citation,
    url: source.url,
    terms: source.terms,
    note: NOTE,
  };
  writeFileSync(
    EXCLUDED_DATASET_URL,
    `{\n  "source": ${JSON.stringify(head, null, 2).replace(/\n/g, '\n  ')},\n  "byPos": {\n${lines.join(',\n')}\n  }\n}\n`,
  );
  console.log(
    `${total} excluded headword keys: ${Object.entries(byPos)
      .map(([t, k]) => `${t} ${k.length}`)
      .join(' · ')}`,
  );
}

main();
